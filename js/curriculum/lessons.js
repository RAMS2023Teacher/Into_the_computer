export const LESSON_IDS = LESSONS.map((l) => l.id);
export const getLesson = (id) => LESSONS.find((l) => l.id === id) || null;

/** The steps a student sees, in order. Lesson 5 adds the steps of the chosen track. */
export function stepsFor(lesson, track) {
  if (!lesson.tracks) return lesson.steps;
  const t = lesson.tracks[track];
  return t ? [lesson.choose, ...t.steps] : [lesson.choose];
}
/** Every step the lesson has, across both project tracks. */
export const allSteps = (lesson) => (lesson.tracks ? [lesson.choose, ...Object.values(lesson.tracks).flatMap((t) => t.steps)] : lesson.steps);
export const rubricFor = (lesson, track) => (lesson.tracks ? (lesson.tracks[track] || lesson.tracks.design).rubric : lesson.rubric);
export const stretchFor = (lesson, track) => (lesson.tracks ? (lesson.tracks[track] ? lesson.tracks[track].stretch : []) : lesson.stretch);
export const checksFor = (lesson, track) => {
  const ids = new Set(stepsFor(lesson, track).map((s) => s.id));
  return lesson.checks.filter((c) => ids.has(c.after));
};
